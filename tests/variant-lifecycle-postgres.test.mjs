import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import pg from "pg";
import request from "supertest";
import { createApp } from "../server/app.mjs";
import { applyMigrations, csrfFrom } from "./admin-test-helpers.mjs";
import { hashPassword } from "../server/security.mjs";

test("retired variants keep orders, stock history and stable IDs on real local PostgreSQL", { skip: !process.env.DATABASE_URL }, async (t) => {
  const base = new pg.Pool({ connectionString: process.env.DATABASE_URL });
  const server = (await base.query("SELECT inet_server_addr() host,current_database() database")).rows[0];
  assert.ok(["127.0.0.1", "::1"].includes(server.host));
  assert.equal(server.database, "melyne_dev");
  const before = (await base.query("SELECT (SELECT COUNT(*) FROM products) products,(SELECT COUNT(*) FROM product_variants) variants,(SELECT COUNT(*) FROM orders) orders")).rows[0];
  const schema = `variant_lifecycle_test_${crypto.randomBytes(8).toString("hex")}`;
  await base.query(`CREATE SCHEMA ${schema}`);
  const db = new pg.Pool({ connectionString: process.env.DATABASE_URL, options: `-c search_path=${schema}` });
  const tempRoot = await fs.mkdtemp(path.join(os.tmpdir(), "melyne-variant-lifecycle-"));
  t.after(async () => {
    await db.end();
    await base.query(`DROP SCHEMA ${schema} CASCADE`);
    const after = (await base.query("SELECT (SELECT COUNT(*) FROM products) products,(SELECT COUNT(*) FROM product_variants) variants,(SELECT COUNT(*) FROM orders) orders")).rows[0];
    assert.deepEqual(after, before);
    await base.end();
    assert.ok(path.resolve(tempRoot).startsWith(path.resolve(os.tmpdir()) + path.sep));
    await fs.rm(tempRoot, { recursive: true, force: true });
  });
  await applyMigrations(db);
  await db.query("INSERT INTO categories(id,slug,name) VALUES('kids','kids','Kids')");
  await db.query("INSERT INTO admin_users(id,email,password_hash) VALUES($1,$2,$3)", [crypto.randomUUID(), "lifecycle@example.test", await hashPassword("local-test-password")]);
  const app = await createApp({ db, config: { uploadRoot: path.join(tempRoot, "uploads"), backupRoot: path.join(tempRoot, "backups"), publicBaseUrl: "http://localhost", allowedOrigins: ["http://localhost"], production: false, sessionSecret: "local-variant-lifecycle-secret-123456", googleSheetsWebhookUrl: null, googleSheetsWebhookSecret: null, orderRateLimit: 1000 } });
  const owner = request.agent(app);
  const login = await owner.post("/api/admin/session").send({ email: "lifecycle@example.test", password: "local-test-password" }).expect(200);
  const csrf = csrfFrom(login);
  const options = (colors) => [{ id: "color", name: "Color", key: "color", values: colors.map((color) => ({ id: color, label: color })) }];
  const variant = (id, color) => ({ id, name: color, selections: [{ option: "Color", optionKey: "color", value: color }], priceMad: 100, stockQuantity: 2, available: true, retired: false, imageId: null });
  const red = variant("lifecycle-red", "Red");
  const blue = variant("lifecycle-blue", "Blue");
  const payload = { slug: "lifecycle-product", originalName: "Lifecycle product", displayName: "Lifecycle product", priceMad: 100, availability: "available", status: "published", categorySlugs: ["kids"], options: options(["Red", "Blue"]), variants: [red, blue], featured: false };
  const created = await owner.post("/api/admin/products").set("x-csrf-token", csrf).send(payload).expect(201);
  const productId = created.body.id;
  const orderBody = { customer: { name: "Local Test", phone: "0600000000", city: "Rabat", address: "Test address" }, items: [{ productId, variantId: blue.id, quantity: 1 }] };
  const order = await request(app).post("/api/orders").set("idempotency-key", crypto.randomUUID()).send(orderBody).expect(201);
  assert.equal((await db.query("SELECT stock_quantity FROM product_variants WHERE id=$1", [blue.id])).rows[0].stock_quantity, 1);

  await owner.put(`/api/admin/products/${productId}`).set("x-csrf-token", csrf).send({ ...payload, options: options(["Red"]), variants: [red] }).expect(200);
  const retired = (await db.query("SELECT id,retired_at,available,stock_quantity FROM product_variants WHERE id=$1", [blue.id])).rows[0];
  assert.equal(retired.id, blue.id);
  assert.ok(retired.retired_at);
  assert.equal(retired.available, false);
  assert.equal(retired.stock_quantity, 1);
  const publicAfterRetire = (await request(app).get("/api/public/storefront").expect(200)).body.products[0];
  assert.deepEqual(publicAfterRetire.variants.map((item) => item.id), [red.id]);
  assert.deepEqual(publicAfterRetire.options[0].values.map((item) => item.label), ["Red"]);
  const ownerAfterRetire = (await owner.get("/api/admin/products").expect(200)).body.products[0];
  assert.equal(ownerAfterRetire.variants.find((item) => item.id === blue.id).retired, true);
  await owner.put(`/api/admin/products/${productId}`).set("x-csrf-token", csrf).send({ ...payload, variants: [red, { ...blue, id: "replacement-blue" }] }).expect(409);
  await request(app).post("/api/orders").set("idempotency-key", crypto.randomUUID()).send(orderBody).expect(409);
  assert.equal((await db.query("SELECT variant_id,variant_snapshot FROM order_items WHERE order_id=$1", [order.body.id])).rows[0].variant_id, blue.id);
  assert.equal((await db.query("SELECT COUNT(*) count FROM stock_movements WHERE variant_id=$1", [blue.id])).rows[0].count, "1");

  await owner.patch(`/api/admin/orders/${order.body.id}`).set("x-csrf-token", csrf).send({ status: "cancelled" }).expect(200);
  assert.equal((await db.query("SELECT stock_quantity,retired_at FROM product_variants WHERE id=$1", [blue.id])).rows[0].stock_quantity, 2);
  assert.equal((await db.query("SELECT COUNT(*) count FROM stock_movements WHERE variant_id=$1", [blue.id])).rows[0].count, "2");
  await owner.put(`/api/admin/products/${productId}`).set("x-csrf-token", csrf).send({ ...payload, variants: [red, { ...blue, retired: false, available: false }] }).expect(200);
  const restored = (await db.query("SELECT retired_at,available,stock_quantity FROM product_variants WHERE id=$1", [blue.id])).rows[0];
  assert.equal(restored.retired_at, null);
  assert.equal(restored.available, false);
  assert.equal(restored.stock_quantity, 2);
  await request(app).post("/api/orders").set("idempotency-key", crypto.randomUUID()).send(orderBody).expect(409);
  await owner.put(`/api/admin/products/${productId}`).set("x-csrf-token", csrf).send(payload).expect(200);
  await request(app).post("/api/orders").set("idempotency-key", crypto.randomUUID()).send(orderBody).expect(201);
  await owner.post(`/api/admin/products/${productId}/archive`).set("x-csrf-token", csrf).send({}).expect(200);
  assert.equal((await request(app).get("/api/public/storefront").expect(200)).body.products.length, 0);
  await owner.post(`/api/admin/products/${productId}/restore`).set("x-csrf-token", csrf).send({}).expect(200);
  assert.equal((await request(app).get("/api/public/storefront").expect(200)).body.products.length, 0);
  assert.equal((await db.query("SELECT COUNT(*) count FROM product_variants WHERE product_id=$1", [productId])).rows[0].count, "2");
});
