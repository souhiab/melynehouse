  await db.query("INSERT INTO admin_users(id,email,password_hash) VALUES($1,$2,$3)", [crypto.randomUUID(), "manual@example.test", await hashPassword("local-test-password")]);
  let sheetCalls = 0;
  const app = await createApp({ db, config: { uploadRoot: path.join(tempRoot, "uploads"), backupRoot: path.join(tempRoot, "backups"), publicBaseUrl: "http://localhost", allowedOrigins: ["http://localhost"], production: false, sessionSecret: "local-order-management-secret-123456", googleSheetsWebhookUrl: "http://127.0.0.1:9/test-only", googleSheetsWebhookSecret: null, orderRateLimit: 1000 }, fetchImpl: async () => { sheetCalls += 1; throw new Error("Manual orders must never call Sheets"); } });
