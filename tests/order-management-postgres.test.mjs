test("website idempotency hashes remain compatible with pre-migration orders", () => {
  const input = { customer: { name: "Test" }, note: "", items: [] };
  const expected = crypto.createHash("sha256").update(JSON.stringify({ customer: input.customer, note: input.note, items: [] })).digest("hex");
  assert.equal(orderRequestHash(input, []), expected);
  assert.notEqual(orderRequestHash(input, [], "whatsapp"), expected);
});

test("owner manual orders use safe stock reservation and private order details on local PostgreSQL", { skip: !process.env.DATABASE_URL }, async (t) => {
  const base = new pg.Pool({ connectionString: process.env.DATABASE_URL });
  const server = (await base.query("SELECT inet_server_addr() host,current_database() database")).rows[0];
  assert.ok(["127.0.0.1", "::1"].includes(server.host));
  assert.equal(server.database, "melyne_dev");
  const before = (await base.query("SELECT (SELECT COUNT(*) FROM products) products,(SELECT COUNT(*) FROM orders) orders")).rows[0];
  const schema = `order_management_test_${crypto.randomBytes(8).toString("hex")}`;
  await base.query(`CREATE SCHEMA ${schema}`);
  const db = new pg.Pool({ connectionString: process.env.DATABASE_URL, options: `-c search_path=${schema}` });
  const tempRoot = await fs.mkdtemp(path.join(os.tmpdir(), "melyne-order-management-"));
  t.after(async () => {
    await db.end();
    await base.query(`DROP SCHEMA ${schema} CASCADE`);
    const after = (await base.query("SELECT (SELECT COUNT(*) FROM products) products,(SELECT COUNT(*) FROM orders) orders")).rows[0];
    assert.deepEqual(after, before);
    await base.end();
    assert.ok(path.resolve(tempRoot).startsWith(path.resolve(os.tmpdir()) + path.sep));
    await fs.rm(tempRoot, { recursive: true, force: true });
  });
  await applyMigrations(db);
  await db.query("INSERT INTO products(id,slug,original_name,display_name,price_mad,availability,status) VALUES('manual-product','manual-product','Manual product','Manual product',100,'available','published')");
  await db.query("INSERT INTO product_variants(id,product_id,name,selections,price_mad,stock_quantity,available) VALUES('manual-variant','manual-product','Blue M',$1,125,2,true)", [JSON.stringify([{ option: "Color", value: "Blue" }, { option: "Size", value: "M" }])]);
  await db.query("INSERT INTO admin_users(id,email,password_hash) VALUES($1,$2,$3)", [crypto.randomUUID(), "manual@example.test", await hashPassword("local-test-password")]);
  const app = await createApp({ db, config: { uploadRoot: path.join(tempRoot, "uploads"), backupRoot: path.join(tempRoot, "backups"), publicBaseUrl: "http://localhost", allowedOrigins: ["http://localhost"], production: false, sessionSecret: "local-order-management-secret-123456", googleSheetsWebhookUrl: null, googleSheetsWebhookSecret: null, orderRateLimit: 1000 } });
  const owner = request.agent(app);
  const login = await owner.post("/api/admin/session").send({ email: "manual@example.test", password: "local-test-password" }).expect(200);
  const csrf = csrfFrom(login);
  const body = { source: "whatsapp", customer: { name: "Local Test", phone: "0600000000", city: "Rabat", address: "Test address" }, items: [{ productId: "manual-product", variantId: "manual-variant", quantity: 1 }] };
  const key = crypto.randomUUID();
  await request(app).post("/api/admin/orders").set("idempotency-key", key).send(body).expect(401);
  await owner.post("/api/admin/orders").set("idempotency-key", key).send(body).expect(403);
  const created = await owner.post("/api/admin/orders").set("x-csrf-token", csrf).set("idempotency-key", key).send(body).expect(201);
  assert.equal(created.body.totalMad, 125);
  assert.equal(created.body.sheetSyncStatus, "disabled");
  const retry = await owner.post("/api/admin/orders").set("x-csrf-token", csrf).set("idempotency-key", key).send(body).expect(200);
  assert.equal(retry.body.id, created.body.id);
  await owner.post("/api/admin/orders").set("x-csrf-token", csrf).set("idempotency-key", key).send({ ...body, source: "instagram" }).expect(409);
  assert.equal((await db.query("SELECT stock_quantity FROM product_variants WHERE id='manual-variant'")).rows[0].stock_quantity, 1);
  const listing = (await owner.get("/api/admin/orders").expect(200)).body;
  assert.equal(listing.page, 1);
  assert.equal(listing.pageSize, 50);
  const listed = listing.orders[0];
  assert.equal(listed.source, "whatsapp");
  assert.equal(listed.customer.name, "Local Test");
  assert.equal(listed.items[0].productSnapshot.displayName, "Manual product");
  assert.equal(listed.items[0].variantSnapshot.selections[1].value, "M");
  assert.deepEqual((await owner.get("/api/admin/orders?page=2").expect(200)).body.orders, []);
  await owner.get("/api/admin/orders?page=bad").expect(400);
  assert.equal((await db.query("SELECT COUNT(*) count FROM stock_movements WHERE order_id=$1", [created.body.id])).rows[0].count, "1");
  await owner.patch(`/api/admin/orders/${created.body.id}`).set("x-csrf-token", csrf).send({ status: "cancelled" }).expect(200);
  assert.equal((await db.query("SELECT stock_quantity FROM product_variants WHERE id='manual-variant'")).rows[0].stock_quantity, 2);
  assert.equal((await db.query("SELECT COUNT(*) count FROM stock_movements WHERE order_id=$1", [created.body.id])).rows[0].count, "2");
  await db.query("UPDATE product_variants SET retired_at=now(),available=false WHERE id='manual-variant'");
  await owner.post("/api/admin/orders").set("x-csrf-token", csrf).set("idempotency-key", crypto.randomUUID()).send(body).expect(409);
});
